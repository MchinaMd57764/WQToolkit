    var effective: String {
        if lang == "zh" || lang == "en" { return lang }
        let p = Locale.preferredLanguages.first ?? "en"
        return p.lowercased().hasPrefix("zh") ? "zh" : "en"
    }

    func t(_ k: String) -> String {
        let table = effective == "zh" ? Self.zh : Self.en
        return table[k] ?? Self.en[k] ?? k
    }

    func f(_ k: String, _ args: CVarArg...) -> String {
        String(format: t(k), arguments: args)
    }

